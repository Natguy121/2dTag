export const MAP_BY_ID = Object.fromEntries(MAPS.map((m) => [m.id, m]));

export function getMap(id) {
  return MAP_BY_ID[id] || MAPS[0];
}

export function randomMapId() {
  return MAPS[Math.floor(Math.random() * MAPS.length)].id;
}
